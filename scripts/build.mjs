// Builds themes/Woody-color-theme.json from the sources in src/.
//
//   node scripts/build.mjs           write the theme file
//   node scripts/build.mjs --check   exit 1 if the theme file is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import colors from '../src/colors.mjs';
import { semanticTokenColors, tokenColors } from '../src/tokens.mjs';

const outFile = fileURLToPath(new URL('../themes/Woody-color-theme.json', import.meta.url));
const header = '// Generated by scripts/build.mjs from src/ — edit those files instead.\n';
const HEX = /^#[0-9a-f]{6}([0-9a-f]{2})?$/;

const theme = {
	$schema: 'vscode://schemas/color-theme',
	name: 'Woody',
	type: 'dark',
	semanticHighlighting: true,
	colors,
	tokenColors,
	semanticTokenColors,
};

function validate() {
	const errors = [];
	const checkColor = (where, value) => {
		if (!HEX.test(value)) errors.push(`${where}: expected lowercase #rrggbb or #rrggbbaa, got ${value}`);
	};

	for (const [key, value] of Object.entries(colors)) checkColor(`colors["${key}"]`, value);

	// A selector that sets the same property in two rules means one rule is dead.
	const seen = new Map();
	for (const { name, scope, settings } of tokenColors) {
		if (Object.hasOwn(settings, 'foreground')) checkColor(`tokenColors "${name}"`, settings.foreground);
		for (const selector of [scope].flat()) {
			for (const property of Object.keys(settings)) {
				const id = `${selector} → ${property}`;
				if (seen.has(id)) console.warn(`warning: "${id}" is set by both "${seen.get(id)}" and "${name}"`);
				else seen.set(id, name);
			}
		}
	}

	for (const [selector, style] of Object.entries(semanticTokenColors)) {
		if (typeof style === 'string') checkColor(`semanticTokenColors["${selector}"]`, style);
		else if (Object.hasOwn(style, 'foreground')) checkColor(`semanticTokenColors["${selector}"]`, style.foreground);
	}

	if (errors.length) {
		console.error(errors.join('\n'));
		process.exit(1);
	}
}

validate();
const output = header + JSON.stringify(theme, null, '\t') + '\n';

if (process.argv.includes('--check')) {
	const current = readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n');
	if (current !== output) {
		console.error('themes/Woody-color-theme.json is out of date. Run `npm run build`.');
		process.exit(1);
	}
	console.log('themes/Woody-color-theme.json is up to date.');
} else {
	writeFileSync(outFile, output);
	console.log(
		`Wrote themes/Woody-color-theme.json (${Object.keys(colors).length} colours, ${tokenColors.length} token rules).`
	);
}
